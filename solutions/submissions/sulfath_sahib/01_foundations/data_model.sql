-- =============================================================================
-- VALIDATION 9 — TRANSACTION DQ RECONCILIATION
-- =============================================================================

-- Expected:
--
-- missing_amount               = 740
-- paid_without_approver        = 1827
-- missing_disputed_amount      = 740
-- -----------------------------------------------------------------------------

SELECT

    SUM(
        CASE

            WHEN amount IS NULL
                THEN 1

            ELSE 0

        END
    ) AS missing_amount,

    SUM(
        CASE

            WHEN paid_without_approver_flag
                THEN 1

            ELSE 0

        END
    ) AS paid_without_approver,

    SUM(
        CASE

            WHEN disputed_amount_missing_flag
                THEN 1

            ELSE 0

        END
    ) AS missing_disputed_amount

FROM fact_transactions
;


-- =============================================================================
-- VALIDATION 10 — MISSING AMOUNT BY PAYMENT STATUS
-- =============================================================================

SELECT

    payment_status,

    COUNT(*)
        AS total_transactions,

    SUM(
        CASE

            WHEN amount IS NULL
                THEN 1

            ELSE 0

        END
    ) AS missing_amount_count

FROM fact_transactions

GROUP BY payment_status

ORDER BY payment_status
;


-- =============================================================================
-- VALIDATION 11 — SAMPLE STAR SCHEMA QUERY
-- =============================================================================

SELECT

    f.transaction_id,

    d.full_date
        AS transaction_date,

    p.project_id,

    p.project_name,

    e.employee_id
        AS approved_by,

    e.full_name
        AS approver_name,

    v.vendor_id,

    v.vendor_name,

    f.category,

    f.amount,

    f.currency,

    f.payment_status,

    f.employee_scd_date_mismatch_flag,

    f.dq_issue_flag

FROM fact_transactions f

INNER JOIN dim_project p

    ON f.project_key
       = p.project_key

INNER JOIN dim_vendor v

    ON f.vendor_key
       = v.vendor_key

INNER JOIN dim_date d

    ON f.date_key
       = d.date_key

LEFT JOIN dim_employee e

    ON f.employee_key
       = e.employee_key

ORDER BY

    d.full_date,

    f.transaction_id

LIMIT 20;