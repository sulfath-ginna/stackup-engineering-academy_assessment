-- =============================================================================
-- STAGING — EMPLOYEES
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Employee master data.
--
-- Invalid hire dates found during source profiling include:
--
--   -999
--   99999-01-01
--
-- DuckDB can represent unusually large years, therefore TRY_CAST alone is not
-- sufficient. An explicit YYYY-MM-DD validation and reasonable date range are
-- applied.
-- -----------------------------------------------------------------------------

CREATE OR REPLACE TEMP VIEW stg_employees AS

SELECT

    CAST(employee_id AS VARCHAR)
        AS employee_id,

    CAST(full_name AS VARCHAR)
        AS full_name,

    CAST(email AS VARCHAR)
        AS email,

    CAST(department AS VARCHAR)
        AS department,

    CAST(role AS VARCHAR)
        AS role,

    CAST(level AS VARCHAR)
        AS level,

    CASE

        WHEN hire_date IS NULL
            THEN NULL

        WHEN NOT REGEXP_MATCHES(
            TRIM(CAST(hire_date AS VARCHAR)),
            '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'
        )
            THEN NULL

        WHEN TRY_CAST(hire_date AS DATE) IS NULL
            THEN NULL

        WHEN TRY_CAST(hire_date AS DATE)
             < DATE '1950-01-01'
            THEN NULL

        WHEN TRY_CAST(hire_date AS DATE)
             > CURRENT_DATE
            THEN NULL

        ELSE TRY_CAST(
            hire_date AS DATE
        )

    END AS hire_date,

    TRY_CAST(salary AS DOUBLE)
        AS salary,

    CAST(manager_id AS VARCHAR)
        AS manager_id,

    CAST(region AS VARCHAR)
        AS region,

    CAST(status AS VARCHAR)
        AS status,

    TRY_CAST(
        years_experience AS INTEGER
    ) AS years_experience

FROM read_csv_auto(
    'datasets/employees.csv',
    header = true
);


