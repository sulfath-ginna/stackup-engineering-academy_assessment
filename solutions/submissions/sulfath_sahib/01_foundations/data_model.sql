-- =============================================================================
-- STACKUP ENGINEERING ACADEMY
-- TASK 1.2 — DIMENSIONAL DATA MODEL
--
-- Database Engine: DuckDB
--
-- Warehouse Model:
--   dim_project
--   dim_employee           -- SCD Type 2
--   dim_vendor
--   dim_date
--   dim_employee_project   -- many-to-many bridge
--   fact_transactions
--
-- Sources:
--   outputs/projects_clean.csv
--   datasets/employees.csv
--   datasets/employees_salary_history.csv
--   outputs/transactions_clean.csv
--
-- DESIGN PRINCIPLES
-- -----------------------------------------------------------------------------
-- 1. All dimensions use integer surrogate keys.
-- 2. Source IDs are preserved as natural/business keys.
-- 3. Employee salary, role and level are handled using SCD Type 2.
-- 4. Multiple employee changes on the same day are collapsed to the final
--    state for that day because transactions contain DATE, not timestamp.
-- 5. Invalid hire dates are converted to NULL.
-- 6. Missing transaction amounts remain NULL; they are not converted to zero.
-- 7. Missing transaction approvers remain NULL.
-- 8. Transactions with valid employee IDs but dates preceding the employee's
--    first SCD record are retained and explicitly flagged.
-- 9. Vendor category is stored in the fact because one vendor can transact
--    under multiple categories.
-- =============================================================================


-- =============================================================================
-- CLEAN EXISTING WAREHOUSE TABLES
