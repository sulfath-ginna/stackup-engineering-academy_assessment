CREATE TABLE dim_vendor
(
    vendor_key INTEGER PRIMARY KEY,

    vendor_id VARCHAR NOT NULL UNIQUE,

    vendor_name VARCHAR
);


INSERT INTO dim_vendor

SELECT

    CAST(
        ROW_NUMBER() OVER
        (
            ORDER BY vendor_id
        )
        AS INTEGER
    ) AS vendor_key,

    vendor_id,

    vendor_name

FROM
(
    SELECT DISTINCT

        CAST(vendor_id AS VARCHAR)
            AS vendor_id,

        CAST(vendor_name AS VARCHAR)
            AS vendor_name

    FROM stg_transactions

    WHERE vendor_id IS NOT NULL
);


-- =============================================================================
-- DIMENSION: DATE
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Grain:
-- One row per calendar date.
--
-- Transaction source date range observed:
--   2022-01-06 to 2026-08-04
--
-- date_key:
-- Integer warehouse surrogate key.
--
-- full_date:
-- Natural calendar date.
-- -----------------------------------------------------------------------------

CREATE TABLE dim_date
(
    date_key INTEGER PRIMARY KEY,

    full_date DATE NOT NULL UNIQUE,

    year INTEGER,

    quarter INTEGER,

    month INTEGER,

    month_name VARCHAR,

    week INTEGER,

    day INTEGER,

    day_name VARCHAR,

    is_weekend BOOLEAN
);


INSERT INTO dim_date

WITH date_bounds AS
(
    SELECT

        MIN(
            TRY_CAST(
                transaction_date AS DATE
            )
        ) AS min_date,

        MAX(
            TRY_CAST(
                transaction_date AS DATE
            )
        ) AS max_date

    FROM stg_transactions
),

calendar AS
(
    SELECT

        CAST(
            generate_series AS DATE
        ) AS full_date

    FROM date_bounds,

    generate_series(
        min_date,
        max_date,
        INTERVAL 1 DAY
    )
)


SELECT

    CAST(
        ROW_NUMBER() OVER
        (
            ORDER BY full_date
        )
        AS INTEGER
    ) AS date_key,

    full_date,

    CAST(
        EXTRACT(
            YEAR FROM full_date
        )
        AS INTEGER
    ) AS year,

    CAST(
        EXTRACT(
            QUARTER FROM full_date
        )
        AS INTEGER
    ) AS quarter,

    CAST(
        EXTRACT(
            MONTH FROM full_date
        )
        AS INTEGER
    ) AS month,

    STRFTIME(
        full_date,
        '%B'
    ) AS month_name,

    CAST(
        EXTRACT(
            WEEK FROM full_date
        )
        AS INTEGER
    ) AS week,

    CAST(
        EXTRACT(
            DAY FROM full_date
        )
        AS INTEGER
    ) AS day,

    STRFTIME(
        full_date,
        '%A'
    ) AS day_name,

    CASE

        WHEN EXTRACT(
            ISODOW FROM full_date
        ) IN (6, 7)

            THEN TRUE

        ELSE FALSE

    END AS is_weekend

FROM calendar;


-- =============================================================================
-- BRIDGE: EMPLOYEE ↔ PROJECT
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Employee/project is many-to-many.
--
-- Observable relationships available in the source:
--
--   projects.project_manager_id
--       -> Project Manager
--
--   transactions.approved_by
--       -> Transaction Approver
--
-- The bridge resolves these relationships using the CURRENT employee dimension
-- row. Historical employee versions remain available through fact_transactions.
-- -----------------------------------------------------------------------------

CREATE TABLE dim_employee_project
(
    employee_project_key INTEGER PRIMARY KEY,

    employee_key INTEGER NOT NULL,

    project_key INTEGER NOT NULL,

    relationship_type VARCHAR NOT NULL,

    FOREIGN KEY (employee_key)
        REFERENCES dim_employee(employee_key),

    FOREIGN KEY (project_key)
        REFERENCES dim_project(project_key)
);


INSERT INTO dim_employee_project

WITH employee_project_relationships AS
(
    -- -------------------------------------------------------------------------
    -- Project manager relationship
    -- -------------------------------------------------------------------------

    SELECT DISTINCT

        CAST(
            project_manager_id AS VARCHAR
        ) AS employee_id,

        CAST(
            project_id AS VARCHAR
        ) AS project_id,

        'Project Manager'
            AS relationship_type

    FROM stg_projects

    WHERE project_manager_id
          IS NOT NULL


    UNION


    -- -------------------------------------------------------------------------
    -- Transaction approver relationship
    -- -------------------------------------------------------------------------

    SELECT DISTINCT

        CAST(
            approved_by AS VARCHAR
        ) AS employee_id,

        CAST(
            project_id AS VARCHAR
        ) AS project_id,

        'Transaction Approver'
            AS relationship_type

    FROM stg_transactions

    WHERE approved_by IS NOT NULL

      AND TRIM(
            CAST(
                approved_by AS VARCHAR
            )
          ) <> ''
),

resolved_relationships AS
(
    SELECT

        e.employee_key,

        p.project_key,

        r.relationship_type

    FROM employee_project_relationships r

    INNER JOIN dim_employee e

        ON r.employee_id
           = e.employee_id

       AND e.is_current
           = TRUE

    INNER JOIN dim_project p

        ON r.project_id
           = p.project_id
)


SELECT

    CAST(
        ROW_NUMBER() OVER
        (
            ORDER BY

                employee_key,

                project_key,

                relationship_type
        )
        AS INTEGER
    ) AS employee_project_key,

    employee_key,

    project_key,

    relationship_type

FROM resolved_relationships;


-- =============================================================================
-- FACT TABLE: TRANSACTIONS
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Grain:
-- One row per source transaction.
--
-- Expected source rows:
--   50,000
--
-- Foreign keys:
--
--   project_key
--       -> dim_project
--
--   employee_key
--       -> dim_employee
--
--   vendor_key
--       -> dim_vendor
--
--   date_key
--       -> dim_date
--
--
-- EMPLOYEE SCD RESOLUTION
-- -----------------------------------------------------------------------------
-- Preferred employee_key:
-- Employee version whose valid date range contains transaction_date.
--
-- Source profiling identified 219 transactions where:
--
--   approved_by is valid
--   BUT transaction_date is earlier than that employee's first SCD version.
--
-- These rows are retained by resolving them to the employee's FIRST known SCD
-- version and setting employee_scd_date_mismatch_flag = TRUE.
--
-- This avoids:
--   - losing transactions
--   - fabricating an employee ID
--   - silently changing historical SCD dates
--
-- Missing approved_by remains NULL.
-- -----------------------------------------------------------------------------

CREATE TABLE fact_transactions
(
    transaction_key BIGINT PRIMARY KEY,

    transaction_id VARCHAR NOT NULL UNIQUE,

    project_key INTEGER NOT NULL,

    employee_key INTEGER,

    vendor_key INTEGER NOT NULL,

    date_key INTEGER NOT NULL,

    category VARCHAR,

    amount DOUBLE,

    currency VARCHAR,

    payment_status VARCHAR,

    invoice_ref VARCHAR,

    notes VARCHAR,

    amount_missing_flag BOOLEAN,

    approver_missing_flag BOOLEAN,

    paid_without_approver_flag BOOLEAN,

    disputed_amount_missing_flag BOOLEAN,

    notes_missing_flag BOOLEAN,

    employee_scd_date_mismatch_flag BOOLEAN,

    dq_issue_flag BOOLEAN,

    FOREIGN KEY (project_key)
        REFERENCES dim_project(project_key),

    FOREIGN KEY (employee_key)
        REFERENCES dim_employee(employee_key),

    FOREIGN KEY (vendor_key)
        REFERENCES dim_vendor(vendor_key),

    FOREIGN KEY (date_key)
        REFERENCES dim_date(date_key)
);


INSERT INTO fact_transactions

WITH transaction_base AS
(
    SELECT

        t.*,

        TRY_CAST(
            t.transaction_date AS DATE
        ) AS transaction_date_parsed

    FROM stg_transactions t
),


-- -----------------------------------------------------------------------------
-- Exact SCD match.
-- -----------------------------------------------------------------------------

exact_employee_match AS
(
    SELECT

        t.transaction_id,

        e.employee_key

    FROM transaction_base t

    INNER JOIN dim_employee e

        ON CAST(
            t.approved_by AS VARCHAR
        ) = e.employee_id

       AND t.transaction_date_parsed
           BETWEEN e.valid_from
               AND e.valid_to
),


-- -----------------------------------------------------------------------------
-- First known SCD record for each employee.
--
-- Used only as a fallback for valid employee IDs where transaction_date occurs
-- before the first known employee version.
-- -----------------------------------------------------------------------------

first_employee_version AS
(
    SELECT

        employee_id,

        employee_key,

        valid_from,

        ROW_NUMBER() OVER
        (
            PARTITION BY employee_id

            ORDER BY
                valid_from,
                employee_key
        ) AS rn

    FROM dim_employee
),


resolved_transactions AS
(
    SELECT

        t.*,

        exact.employee_key
            AS exact_employee_key,

        first_version.employee_key
            AS fallback_employee_key,

        CASE

            WHEN t.approved_by IS NULL
                THEN FALSE

            WHEN TRIM(
                CAST(
                    t.approved_by AS VARCHAR
                )
            ) = ''
                THEN FALSE

            WHEN exact.employee_key
                 IS NOT NULL
                THEN FALSE

            WHEN first_version.employee_key
                 IS NOT NULL
                THEN TRUE

            ELSE FALSE

        END AS employee_scd_date_mismatch_flag

    FROM transaction_base t

    LEFT JOIN exact_employee_match exact

        ON CAST(
            t.transaction_id AS VARCHAR
        ) = exact.transaction_id

    LEFT JOIN first_employee_version first_version

        ON CAST(
            t.approved_by AS VARCHAR
        ) = first_version.employee_id

       AND first_version.rn = 1
)


SELECT

    CAST(
        ROW_NUMBER() OVER
        (
            ORDER BY transaction_id
        )
        AS BIGINT
    ) AS transaction_key,

    CAST(
        transaction_id AS VARCHAR
    ) AS transaction_id,

    p.project_key,

    CASE

        WHEN exact_employee_key IS NOT NULL
            THEN exact_employee_key

        WHEN approver_missing_flag
            THEN NULL

        ELSE fallback_employee_key

    END AS employee_key,

    v.vendor_key,

    d.date_key,

    CAST(
        category AS VARCHAR
    ) AS category,

    TRY_CAST(
        amount AS DOUBLE
    ) AS amount,

    CAST(
        currency AS VARCHAR
    ) AS currency,

    CAST(
        payment_status AS VARCHAR
    ) AS payment_status,

    CAST(
        invoice_ref AS VARCHAR
    ) AS invoice_ref,

    CAST(
        notes AS VARCHAR
    ) AS notes,

    COALESCE(
        TRY_CAST(
            amount_missing_flag
            AS BOOLEAN
        ),
        FALSE
    ) AS amount_missing_flag,

    COALESCE(
        TRY_CAST(
            approver_missing_flag
            AS BOOLEAN
        ),
        FALSE
    ) AS approver_missing_flag,

    COALESCE(
        TRY_CAST(
            paid_without_approver_flag
            AS BOOLEAN
        ),
        FALSE
    ) AS paid_without_approver_flag,

    COALESCE(
        TRY_CAST(
            disputed_amount_missing_flag
            AS BOOLEAN
        ),
        FALSE
    ) AS disputed_amount_missing_flag,

    COALESCE(
        TRY_CAST(
            notes_missing_flag
            AS BOOLEAN
        ),
        FALSE
    ) AS notes_missing_flag,

    employee_scd_date_mismatch_flag,

    (
        COALESCE(
            TRY_CAST(
                dq_issue_flag AS BOOLEAN
            ),
            FALSE
        )

        OR employee_scd_date_mismatch_flag
    ) AS dq_issue_flag

FROM resolved_transactions t

INNER JOIN dim_project p

    ON CAST(
        t.project_id AS VARCHAR
    ) = p.project_id

INNER JOIN dim_vendor v

    ON CAST(
        t.vendor_id AS VARCHAR
    ) = v.vendor_id

INNER JOIN dim_date d

    ON t.transaction_date_parsed
       = d.full_date
;


