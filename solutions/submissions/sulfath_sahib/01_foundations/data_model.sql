-- =============================================================================
-- DIMENSION: EMPLOYEE — SCD TYPE 2
-- =============================================================================

-- -----------------------------------------------------------------------------
-- Grain:
-- One row per employee version.
--
-- Historical SCD attributes:
--   salary
--   role
--   level
--
-- Source salary-history rows describe changes in those attributes.
--
-- Static/current attributes such as:
--   full_name
--   email
--   department
--   manager_id
--   region
--   status
--
-- are not historically tracked by the salary history source, so the current
-- employee-master values are copied across SCD versions.
--
-- Same-day history:
-- EMP0084 contains two employee changes on 2025-03-02.
--
-- Since transaction_date contains only a DATE and has no timestamp, two states
-- occurring within the same calendar day cannot be differentiated reliably.
-- The final state for that date is therefore retained in dim_employee.
-- -----------------------------------------------------------------------------

CREATE TABLE dim_employee
(
    employee_key INTEGER PRIMARY KEY,

    employee_id VARCHAR NOT NULL,

    full_name VARCHAR,

    email VARCHAR,

    department VARCHAR,

    role VARCHAR,

    level VARCHAR,

    hire_date DATE,

    salary DOUBLE,

    manager_id VARCHAR,

    region VARCHAR,

    status VARCHAR,

    years_experience INTEGER,

    valid_from DATE NOT NULL,

    valid_to DATE NOT NULL,

    is_current BOOLEAN NOT NULL,

    change_type VARCHAR,

    change_reason VARCHAR
);


INSERT INTO dim_employee

WITH history_ranked AS
(
    SELECT

        h.*,

        ROW_NUMBER() OVER
        (
            PARTITION BY
                h.employee_id,
                h.effective_date

            ORDER BY

                CASE h.change_type

                    WHEN 'Hire'
                        THEN 1

                    WHEN 'Annual Raise'
                        THEN 2

                    WHEN 'Promotion'
                        THEN 3

                    ELSE 4

                END,

                h.new_salary,

                h.new_role,

                h.new_level

        ) AS same_day_sequence,

        COUNT(*) OVER
        (
            PARTITION BY
                h.employee_id,
                h.effective_date
        ) AS same_day_count

    FROM stg_employee_salary_history h
),


-- -----------------------------------------------------------------------------
-- Retain the final employee state for each employee/date combination.
-- -----------------------------------------------------------------------------

history_daily_final AS
(
    SELECT *

    FROM history_ranked

    WHERE same_day_sequence
          = same_day_count
),


-- -----------------------------------------------------------------------------
-- Obtain next effective date for each employee version.
-- -----------------------------------------------------------------------------

history_with_next_date AS
(
    SELECT

        employee_id,

        new_salary,

        new_role,

        new_level,

        effective_date,

        change_type,

        change_reason,

        LEAD(effective_date) OVER
        (
            PARTITION BY employee_id
            ORDER BY effective_date
        ) AS next_effective_date,

        ROW_NUMBER() OVER
        (
            PARTITION BY employee_id
            ORDER BY effective_date
        ) AS employee_version_number

    FROM history_daily_final
),


-- -----------------------------------------------------------------------------
-- Build SCD versions for employees with history.
-- -----------------------------------------------------------------------------

history_versions AS
(
    SELECT

        e.employee_id,

        e.full_name,

        e.email,

        e.department,

        h.new_role
            AS role,

        h.new_level
            AS level,

        e.hire_date,

        h.new_salary
            AS salary,

        e.manager_id,

        e.region,

        e.status,

        e.years_experience,

        h.effective_date
            AS valid_from,

        CASE

            WHEN h.next_effective_date
                 IS NULL

                THEN DATE '9999-12-31'

            ELSE CAST(
                h.next_effective_date
                - INTERVAL 1 DAY
                AS DATE
            )

        END AS valid_to,

        CASE

            WHEN h.next_effective_date
                 IS NULL

                THEN TRUE

            ELSE FALSE

        END AS is_current,

        h.change_type,

        h.change_reason

    FROM history_with_next_date h

    INNER JOIN stg_employees e

        ON h.employee_id
           = e.employee_id
),


-- -----------------------------------------------------------------------------
-- Employees without salary history receive one current dimension record.
--
-- Invalid/missing hire dates use 1900-01-01 as the technical warehouse lower
-- bound. The original hire_date remains NULL in the descriptive hire_date
-- column.
-- -----------------------------------------------------------------------------

employees_without_history AS
(
    SELECT

        e.employee_id,

        e.full_name,

        e.email,

        e.department,

        e.role,

        e.level,

        e.hire_date,

        e.salary,

        e.manager_id,

        e.region,

        e.status,

        e.years_experience,

        COALESCE(
            e.hire_date,
            DATE '1900-01-01'
        ) AS valid_from,

        DATE '9999-12-31'
            AS valid_to,

        TRUE
            AS is_current,

        'Current Record'
            AS change_type,

        'No salary history available'
            AS change_reason

    FROM stg_employees e

    WHERE NOT EXISTS
    (
        SELECT 1

        FROM stg_employee_salary_history h

        WHERE h.employee_id
              = e.employee_id
    )
),


-- -----------------------------------------------------------------------------
-- Combine historical and no-history employee records.
-- -----------------------------------------------------------------------------

all_employee_versions AS
(
    SELECT *

    FROM history_versions


    UNION ALL


    SELECT *

    FROM employees_without_history
)


SELECT

    CAST(
        ROW_NUMBER() OVER
        (
            ORDER BY

                employee_id,

                valid_from,

                salary
        )
        AS INTEGER
    ) AS employee_key,

    employee_id,

    full_name,

    email,

    department,

    role,

    level,

    hire_date,

    salary,

    manager_id,

    region,

    status,

    years_experience,

    valid_from,

    valid_to,

    is_current,

    change_type,

    change_reason

FROM all_employee_versions;


