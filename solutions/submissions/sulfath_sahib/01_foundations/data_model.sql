-- -----------------------------------------------------------------------------
-- Grain:
-- One row per vendor.
--
-- Source inspection confirmed:
--   25 vendor IDs
--   25 vendor names
--   no vendor_id -> multiple vendor_name conflicts
--
-- Transaction category is NOT stored here because the same vendor can appear
