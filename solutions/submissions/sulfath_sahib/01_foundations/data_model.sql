-- Because one same-day duplicate employee state is collapsed:
--
-- Expected dim_employee total:
--   2231
--
-- Expected distinct employees:
--   1000
--
-- Expected current versions:
--   1000
--
-- Expected historical versions:
--   1231
-- -----------------------------------------------------------------------------

SELECT

    COUNT(*)
        AS total_versions,

    COUNT(
        DISTINCT employee_id
    ) AS employees,

    SUM(
        CASE

            WHEN is_current
                THEN 1

            ELSE 0

        END
    ) AS current_versions,

    SUM(
        CASE

            WHEN NOT is_current
                THEN 1

            ELSE 0

        END
    ) AS historical_versions

FROM dim_employee
;


-- =============================================================================
-- VALIDATION 3 — EXACTLY ONE CURRENT VERSION PER EMPLOYEE
-- =============================================================================

-- Expected:
-- zero rows

SELECT

    employee_id,

    COUNT(*)
        AS current_count

FROM dim_employee

WHERE is_current = TRUE

GROUP BY employee_id

HAVING COUNT(*) <> 1
;


-- =============================================================================
-- VALIDATION 4 — INVALID SCD DATE RANGES
-- =============================================================================

-- Expected:
-- zero rows

SELECT

    employee_id,

    employee_key,

    valid_from,

    valid_to,

    role,

    level,

    salary

FROM dim_employee

WHERE valid_to
      < valid_from

ORDER BY

    employee_id,

    valid_from
;


-- =============================================================================
-- VALIDATION 5 — OVERLAPPING SCD DATE RANGES
-- =============================================================================

-- Expected:
-- zero rows

SELECT

    a.employee_id,

    a.employee_key
        AS employee_key_1,

    a.valid_from
        AS valid_from_1,

    a.valid_to
        AS valid_to_1,

    b.employee_key
        AS employee_key_2,

    b.valid_from
        AS valid_from_2,

    b.valid_to
        AS valid_to_2

FROM dim_employee a

INNER JOIN dim_employee b

    ON a.employee_id
       = b.employee_id

   AND a.employee_key
       < b.employee_key

   AND a.valid_from
       <= b.valid_to

   AND b.valid_from
       <= a.valid_to

ORDER BY a.employee_id
;


-- =============================================================================
-- VALIDATION 6 — CURRENT EMPLOYEE STATE VS SOURCE MASTER
-- =============================================================================

-- Expected:
-- zero rows

SELECT

    d.employee_id,

    d.salary
        AS dimension_salary,

    e.salary
        AS source_salary,

    d.role
        AS dimension_role,

    e.role
        AS source_role,

    d.level
        AS dimension_level,

    e.level
        AS source_level

FROM dim_employee d

INNER JOIN stg_employees e

    ON d.employee_id
       = e.employee_id

WHERE d.is_current
      = TRUE

  AND
  (
        d.salary
        <> e.salary

        OR COALESCE(
            d.role,
            ''
        )
        <> COALESCE(
            e.role,
            ''
        )

        OR COALESCE(
            d.level,
            ''
        )
        <> COALESCE(
            e.level,
            ''
        )
  )
;


-- =============================================================================
-- VALIDATION 7 — FACT TABLE
-- =============================================================================

-- Expected:
--
-- fact_rows                = 50000
-- distinct_transactions    = 50000
-- missing_project_key      = 0
-- missing_vendor_key       = 0
-- missing_date_key         = 0
-- null_employee_key        = 2444
--
-- 2444 is expected because those source transactions genuinely have no
-- approved_by value.
-- -----------------------------------------------------------------------------

SELECT

    COUNT(*)
        AS fact_rows,

    COUNT(
        DISTINCT transaction_id
    ) AS distinct_transactions,

    SUM(
        CASE

            WHEN project_key IS NULL
                THEN 1

            ELSE 0

        END
    ) AS missing_project_key,

    SUM(
        CASE

            WHEN vendor_key IS NULL
                THEN 1

            ELSE 0

        END
    ) AS missing_vendor_key,

    SUM(
        CASE

            WHEN date_key IS NULL
                THEN 1

            ELSE 0

        END
    ) AS missing_date_key,

    SUM(
        CASE

            WHEN employee_key IS NULL
                THEN 1

            ELSE 0

        END
    ) AS null_employee_key

FROM fact_transactions
;


